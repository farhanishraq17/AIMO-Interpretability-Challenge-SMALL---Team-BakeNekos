"""What would it cost to label the rest of the olympiad pool, and is that affordable?

`plan_shards.py` sizes one run. This sizes the whole remaining labelling programme, because the
question that keeps recurring is strategic: the pool holds 505 problems and we have labelled 49
of them, so is the gap a compute problem or not?

Every input is measured from a completed run rather than assumed, and the two phases are priced
separately because they behave differently: the base phase pays for problems the model cannot
solve, and the variants phase only runs on the ones it can.

The throughput figures carry a real uncertainty that this script does not hide. Skywork ran its
base phase at 117 tok/s and its variants phase at 20 tok/s under a byte-identical vLLM config on
the same platform, so both are reported as a range, and the pessimistic column is the honest one
to plan against until a second Skywork variants run says otherwise.

Writes the `Labelling cost model` section of RESULTS.md.

Run:  uv run python ../datagen/plan_labelling_cost.py
"""

from __future__ import annotations

import argparse
import glob
import json
import sys
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "train"))
from results_io import upsert_section  # noqa: E402

RESULTS = ROOT / "RESULTS.md"
POOL = ROOT / "data" / "olympiad_pool" / "pool.parquet"
VARIANTS = ROOT / "data" / "perturbations" / "variants.parquet"

# Measured runs: (model, phase) -> (records glob, metadata glob, gpus).
RUNS = {
    ("Qwen3.5-4B", "base"): ("runs/e20-base-qwen35-gapfill/*/base/shard_*", 1),
    ("Qwen3.5-4B", "variants"): ("runs/e18-variants-qwen35/*/variants/shard_*", 1),
    ("Skywork-7B", "base"): ("runs/e22-base-skywork-gapfill/*/base/shard_*", 2),
    ("Skywork-7B", "variants"): ("runs/e19-variants-skywork/*/variants/shard_*", 2),
    ("Olmo-7B-Think", "base"): ("runs/e17-base-olmo-think/*/base/shard_*", 2),
}
# Four aliases in Secrets.env, ~30 GPU-hours each per week (CLAUDE.md, "Kaggle fleet").
ACCOUNTS, HOURS_PER_ACCOUNT_WEEK = 4, 30

# Pool-wide eligibility from the *full* base phases (Findings 25-26, experiments.md), as
# eligible/sampled. These must not be recomputed from the gapfill runs in RUNS: E20 and E22
# resampled problems chosen because an earlier run had already found them eligible, so their
# rates (68% and 96%) are selection-biased far above the truth and would halve the cost estimate.
# Those runs live on accounts this checkout cannot read, so the rates are constants with a
# citation rather than a measurement.
POOL_ELIGIBILITY = {
    "Qwen3.5-4B": (90, 285),
    "Skywork-7B": (157, 246),
    "Olmo-7B-Think": (17, 30),
}


def measure(pattern: str, gpus: int) -> dict:
    """GPU-seconds per completed item, from the records and metadata a run actually wrote."""
    items, seconds = 0, 0.0
    for directory in sorted(glob.glob(str(ROOT / pattern))):
        path = Path(directory)
        records = [json.loads(line) for line in (path / "records.jsonl").read_text(encoding="utf-8").splitlines() if line.strip()]
        metadata = json.loads((path / "metadata.json").read_text(encoding="utf-8"))
        items += len(records)
        seconds += float(metadata.get("generation_seconds") or 0.0)
    return {"items": items, "gpu_seconds_per_item": seconds * gpus / items if items else float("nan")}


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--weeks", type=float, default=6.0, help="weeks left before the 1 Nov deadline")
    args = parser.parse_args()

    pool = pd.read_parquet(POOL)
    variants = pd.read_parquet(VARIANTS)
    modulus = variants[variants["category"] == "answer_modulus"]
    # Only `distinct` categories may carry labels (transforms.py); answer_modulus is the only one.
    per_problem = len(modulus) / modulus["problem_key"].nunique()
    covered = modulus["problem_key"].nunique()

    measured = {key: measure(pattern, gpus) for key, (pattern, gpus) in RUNS.items()}
    eligibility = {model: hit / total for model, (hit, total) in POOL_ELIGIBILITY.items()}

    budget = ACCOUNTS * HOURS_PER_ACCOUNT_WEEK * args.weeks
    lines = [
        f"Cost of labelling the remaining olympiad pool, from measured throughput. "
        f"Regenerated by `datagen/plan_labelling_cost.py --weeks {args.weeks:g}`.",
        "",
        f"The pool holds **{len(pool)} problems**; `answer_modulus` variants exist for "
        f"**{covered}** of them, {per_problem:.2f} per problem. It is the only `distinct` "
        "category, so it is the only one that may carry labels.",
        "",
        "| Model | Phase | Items measured | GPU-sec/item |",
        "| --- | --- | --- | --- |",
    ]
    for (model, phase), stats in measured.items():
        lines.append(f"| {model} | {phase} | {stats['items']} | {stats['gpu_seconds_per_item']:.0f} |")

    lines += [
        "",
        "Eligibility is pool-wide, from the full base phases (Findings 25-26) — not from the "
        "gapfill runs above, whose problems were picked *because* an earlier run found them "
        "eligible.",
        "",
        "| Model | Eligible | Cost per usable label | Whole pool | Share of budget |",
        "| --- | --- | --- | --- | --- |",
    ]
    for model, rate in eligibility.items():
        base = measured[(model, "base")]["gpu_seconds_per_item"]
        variant_key = (model, "variants")
        if variant_key not in measured:
            lines.append(f"| {model} | {rate:.0%} | *no variants run yet* | -- | -- |")
            continue
        # One base sample per pool problem, but only eligible ones get variants sampled.
        per_label = base / rate + measured[variant_key]["gpu_seconds_per_item"] * per_problem
        whole_pool = per_label * len(pool) * rate / 3600
        lines.append(
            f"| {model} | {rate:.0%} | {per_label / 3600:.2f} GPU-h | "
            f"**{whole_pool:.0f} GPU-h** for ~{len(pool) * rate:.0f} labels | {whole_pool / budget:.0%} |"
        )

    lines += [
        "",
        f"Budget: {ACCOUNTS} reachable accounts x {HOURS_PER_ACCOUNT_WEEK} GPU-hours/week x "
        f"{args.weeks:g} weeks = **{budget:.0f} GPU-hours**.",
        "",
        "Compute is not the binding constraint. The pool itself is: 505 problems cap what any "
        "amount of GPU time can produce, and only the share a model solves 4/4 can be labelled "
        "at all.",
    ]
    upsert_section(RESULTS, "Labelling cost model", "\n".join(lines))
    print("\n".join(lines))


if __name__ == "__main__":
    main()
