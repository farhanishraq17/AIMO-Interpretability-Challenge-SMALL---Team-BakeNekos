"""Do self-generated `answer_modulus` labels agree with official labels? (E20, and gate G-V2 for E24.)

Self-labels measure robustness under a perturbation the rules let us label (`answer_modulus`);
the competition scores robustness under its own seven families. The two are comparable only
where both exist:

* **E20** - DeepSeek's officially labelled Hendrycks MATH problems (Finding 31: kappa -0.135);
* **E24** - the olympiad problems `train-main-v2` labels for each small-track model, which is
  the population the test set is drawn from.

For each set this reports agreement, balanced accuracy, Cohen's kappa with a bootstrap CI over
problems, and the Spearman correlation of our measured drop with the official one. Gate G-V2
(`PLAN.md` §11) passes at kappa >= 0.3 with the CI's lower bound above 0.

Writes the `Self-labels vs official labels` section of RESULTS.md.

Run:  uv run python ../train/compare_selflabels.py
"""

from __future__ import annotations

import argparse
import glob
import sys
from pathlib import Path

import numpy as np
import pandas as pd
from scipy.stats import spearmanr
from sklearn.metrics import balanced_accuracy_score, cohen_kappa_score

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "train"))
from results_io import upsert_section  # noqa: E402

RESULTS = ROOT / "RESULTS.md"
DEEPSEEK = "deepseek-ai/DeepSeek-R1-0528-Qwen3-8B"


def e20_pairs() -> pd.DataFrame | None:
    path = ROOT / "data" / "e7_labels" / "e20-deepseek" / "instances.parquet"
    if not path.is_file():
        return None
    official = pd.read_parquet(ROOT / "data" / "small_track" / "instances_train.parquet")
    official = official[official["model_id"] == DEEPSEEK][["problem_key", "is_robust", "max_absolute_accuracy_decay"]]
    official = official.rename(columns={"is_robust": "official", "max_absolute_accuracy_decay": "official_drop"})
    return pair(pd.read_parquet(path), official)


def e24_pairs() -> pd.DataFrame | None:
    paths = sorted(glob.glob(str(ROOT / "data" / "e7_labels" / "e24-*" / "instances.parquet")))
    labels = ROOT / "data" / "official_check" / "official_labels.parquet"
    if not paths or not labels.is_file():
        return None
    official = pd.read_parquet(labels).rename(columns={"is_robust": "official", "max_drop": "official_drop"})
    frames = []
    for path in paths:
        mine = pd.read_parquet(path)
        model_official = official[official["model_id"] == mine["model_id"].iloc[0]].drop(columns="model_id")
        frames.append(pair(mine, model_official))
    return pd.concat(frames, ignore_index=True)


def pair(mine: pd.DataFrame, official: pd.DataFrame) -> pd.DataFrame:
    mine = mine[mine["is_eligible"]][["model_id", "problem_key", "is_robust", "is_clear_cut", "max_absolute_accuracy_decay"]]
    merged = mine.merge(official, on="problem_key", how="inner")
    merged = merged.rename(columns={"is_robust": "mine", "max_absolute_accuracy_decay": "mine_drop"})
    merged["official"] = merged["official"].astype(bool)
    return merged


def summarise(name: str, frame: pd.DataFrame, rng: np.random.Generator, n_boot: int = 5000) -> str:
    mine, official = frame["mine"].astype(bool).to_numpy(), frame["official"].to_numpy()
    kappa = cohen_kappa_score(official, mine)
    boot = []
    for _ in range(n_boot):
        idx = rng.integers(0, len(frame), len(frame))
        if len(set(official[idx])) > 1 and len(set(mine[idx])) > 1:
            boot.append(cohen_kappa_score(official[idx], mine[idx]))
    low, high = np.percentile(boot, [2.5, 97.5]) if boot else (float("nan"), float("nan"))
    rho = spearmanr(frame["mine_drop"], frame["official_drop"]).statistic
    return (
        f"| {name} | {len(frame)} | {int(mine.sum())} / {int(official.sum())} | {(mine == official).mean():.2f} "
        f"| {balanced_accuracy_score(official, mine):.3f} | {kappa:.3f} [{low:.3f}, {high:.3f}] | {rho:.2f} |"
    )


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--seed", type=int, default=0)
    args = parser.parse_args()
    rng = np.random.default_rng(args.seed)

    lines = [
        "Self-generated `answer_modulus` labels against official labels on the same (model, problem) pairs. "
        "Kappa CIs resample pairs. Gate G-V2 passes at kappa >= 0.3 with the lower bound above 0. "
        "Regenerated by `train/compare_selflabels.py`.",
        "",
        "| Set | Pairs | Robust: ours / official | Agreement | Balanced acc. | Cohen's kappa [95% CI] | Spearman of drops |",
        "| --- | --- | --- | --- | --- | --- | --- |",
    ]
    for name, frame in (("E20: DeepSeek, Hendrycks MATH", e20_pairs()), ("E24: small track, olympiad", e24_pairs())):
        if frame is None or frame.empty:
            lines.append(f"| {name} | not run yet | | | | | |")
            continue
        lines.append(summarise(name, frame, rng))
        clear = frame[frame["is_clear_cut"]]
        if 0 < len(clear) < len(frame):
            lines.append(summarise(f"{name}, clear-cut only", clear, rng))
    upsert_section(RESULTS, "Self-labels vs official labels", "\n".join(lines))
    print("\n".join(lines))


if __name__ == "__main__":
    main()
