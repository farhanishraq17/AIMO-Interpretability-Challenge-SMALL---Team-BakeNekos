"""E23: do familiarity and contamination scores predict robustness? Gate G-M.

`datagen/extract_familiarity.py` scored every labelled problem under each small-track model.
The test is built so the direction of each signal is never chosen on the data it is judged on:

1. **MATH, DeepSeek's labels.** Each signal's AUC against DeepSeek's 142 Hendrycks MATH
   instances, raw and within problem-length quintiles (length drives every text signal here,
   Finding 22). The sign of the within-length AUC fixes the signal's direction.
2. **Official olympiad problems, pooled labels.** The signal, averaged over the four models and
   oriented by step 1, is scored on the E22 harness: problem-level, template-grouped CI and a
   permutation p (Finding 46).

Also scored: each model's NLL minus the mean of the other three (`relative_nll`), the classic
reference-model calibration, which only exists once all four runs are in.

Gate G-M (`PLAN.md` §11): the E22 CI lower bound above 0.5 **and** a within-length MATH AUC
above 0.6 in the same direction. Writes the `E23: familiarity and contamination` section.

Run:  uv run python ../train/eval_familiarity.py
"""

from __future__ import annotations

import argparse
import glob
import sys
from pathlib import Path

import numpy as np
import pandas as pd
from sklearn.metrics import roc_auc_score

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "train"))

from eval_label_free import within_length_auc  # noqa: E402
from eval_problem_level import load_problems, score  # noqa: E402
from results_io import upsert_section  # noqa: E402

RECORDS = "runs/e23-familiarity-*/features/familiarity-*/shard_*/records.jsonl"
INSTANCES = ROOT / "data" / "small_track" / "instances_train.parquet"
RESULTS = ROOT / "RESULTS.md"
DEEPSEEK = "deepseek-ai/DeepSeek-R1-0528-Qwen3-8B"
SIGNALS = ("mean_nll", "min_k_10", "min_k_20", "min_k_pp_20", "zlib_ratio", "suffix_nll", "relative_nll")


def load_scores() -> pd.DataFrame:
    """One row per (problem, scoring model), with `relative_nll` against the other models."""
    paths = sorted(glob.glob(str(ROOT / RECORDS)))
    if not paths:
        raise SystemExit(f"no E23 records match {RECORDS}; download e23-familiarity-a/b first")
    frame = pd.concat([pd.read_json(p, lines=True, dtype={"problem_key": str}) for p in paths], ignore_index=True)
    frame = frame.drop_duplicates(["problem_key", "scored_model_id"])
    total = frame.groupby("problem_key")["mean_nll"].transform("sum")
    count = frame.groupby("problem_key")["mean_nll"].transform("count")
    frame["relative_nll"] = np.where(count > 1, frame["mean_nll"] - (total - frame["mean_nll"]) / (count - 1), np.nan)
    return frame


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--seed", type=int, default=0)
    args = parser.parse_args()
    rng = np.random.default_rng(args.seed)

    scores = load_scores()
    models = sorted(scores["scored_model_id"].unique())
    math = pd.read_parquet(INSTANCES)
    math = math[(math["model_id"] == DEEPSEEK) & math["dataset_id"].str.startswith("hendrycks")]
    math = math.merge(scores[scores["scored_model_id"] == DEEPSEEK], on="problem_key", how="inner")
    y_math = math["is_robust"].astype(bool).to_numpy()
    length = math["problem"].str.len().to_numpy()

    problems = load_problems()
    pooled = scores.groupby("problem_key")[list(SIGNALS)].mean()
    problems = problems.join(pooled, on="problem_key", how="inner")
    y_off = problems["label"].astype(bool).to_numpy()
    groups = problems["template"].to_numpy()

    lines = [
        f"Scored under {len(models)} model(s): {', '.join(f'`{m}`' for m in models)}. MATH: DeepSeek's "
        f"{len(math)} Hendrycks MATH instances, DeepSeek's own scores. Official: {len(problems)} labelled "
        "`train-main-v2` problems, the signal averaged over the models and **oriented by its MATH "
        "within-length direction**, scored on the E22 harness. Regenerated by `train/eval_familiarity.py`.",
        "",
        "| Signal | MATH AUC | MATH within length | Official AUC (oriented) | 95% CI | p | G-M |",
        "| --- | --- | --- | --- | --- | --- | --- |",
    ]
    for signal in SIGNALS:
        valid = math[signal].notna().to_numpy()
        if valid.sum() < 10 or problems[signal].isna().all():
            lines.append(f"| `{signal}` | needs all four models | | | | | |")
            continue
        raw = roc_auc_score(y_math[valid], math.loc[valid, signal])
        within = within_length_auc(y_math[valid], math.loc[valid, signal].to_numpy(), length[valid])
        sign = 1.0 if within >= 0.5 else -1.0
        official = problems[signal].notna().to_numpy()
        result = score(y_off[official], sign * problems.loc[official, signal].to_numpy(), groups[official], rng)
        passes = result["low"] > 0.5 and max(within, 1 - within) > 0.6
        lines.append(
            f"| `{signal}` | {raw:.3f} | {within:.3f} | {result['auc']:.3f} | [{result['low']:.3f}, "
            f"{result['high']:.3f}] | {result['p']:.3f} | {'**pass**' if passes else 'fail'} |"
        )
    lines += [
        "",
        "MATH columns are raw AUCs, so below 0.5 means higher scores go with spurious; the official "
        "column is oriented, so above 0.5 means the MATH direction held on olympiad problems.",
    ]
    upsert_section(RESULTS, "E23: familiarity and contamination", "\n".join(lines))
    print("\n".join(lines))


if __name__ == "__main__":
    main()
