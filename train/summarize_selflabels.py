"""Inventory the self-generated olympiad labels, and test whether models agree on them.

`label.py` writes one directory per model, and the interesting questions cut across those
directories: how many labels each model has, and whether two models that solved the same pool
problem also agree on whether it is robust. Finding 36 measured that agreement on the
organizers' 34 labelled rows and found 20/20 among small-track models; this is the same test on
our own `answer_modulus` labels, where the sample is ours to grow.

The agreement chance rate is the one that matters and is easy to get wrong. Both label sets are
heavily robust, so two independent always-robust labellers would already agree most of the time.
The null here is "each model's label drawn independently at its own observed base rate", which
is what `chance` reports -- not 0.5.

Writes the `Self-generated olympiad labels` section of RESULTS.md.

Run:  uv run python ../train/summarize_selflabels.py
"""

from __future__ import annotations

import argparse
import itertools
import sys
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "train"))
from results_io import upsert_section  # noqa: E402

RESULTS = ROOT / "RESULTS.md"
# One directory per model, as written by datagen/perturb/label.py --out-dir.
LABEL_DIRS = {
    "Qwen/Qwen3.5-4B": ROOT / "data" / "qwen35_labels",
    "Skywork/Skywork-OR1-Math-7B": ROOT / "data" / "skywork_labels",
}


def load(path: Path) -> pd.DataFrame | None:
    table = path / "instances_train.parquet"
    return pd.read_parquet(table) if table.exists() else None


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--n-permutations", type=int, default=20000)
    parser.add_argument("--seed", type=int, default=0)
    args = parser.parse_args()

    tables = {model: table for model, path in LABEL_DIRS.items() if (table := load(path)) is not None}
    if not tables:
        raise SystemExit("no self-label directories found; run datagen/perturb/label.py first")

    lines = [
        "Self-generated `answer_modulus` labels on the olympiad pool, by "
        "`datagen/perturb/label.py`. Regenerated by `train/summarize_selflabels.py`.",
        "",
        "| Model | Train-ready | Robust | Robust rate |",
        "| --- | --- | --- | --- |",
    ]
    for model, table in tables.items():
        n, robust = len(table), int(table["is_robust"].sum())
        lines.append(f"| `{model}` | {n} | {robust} | {robust / n:.3f} |")

    lines += ["", "### Cross-model agreement on shared problems", ""]
    if len(tables) < 2:
        lines.append("Only one model has self-labels; agreement is not yet measurable.")
    else:
        lines += ["| Pair | Shared | Agree | Rate | Chance | p |", "| --- | --- | --- | --- | --- | --- |"]
        for left, right in itertools.combinations(tables, 2):
            a = tables[left].set_index("problem_key")["is_robust"]
            b = tables[right].set_index("problem_key")["is_robust"]
            shared = sorted(set(a.index) & set(b.index))
            if not shared:
                lines.append(f"| `{left}` vs `{right}` | 0 | -- | -- | -- | -- |")
                continue
            agree = int((a.loc[shared].to_numpy() == b.loc[shared].to_numpy()).sum())
            # Independent draws at each model's own observed rate, not a coin flip.
            pa, pb = a.mean(), b.mean()
            chance = pa * pb + (1 - pa) * (1 - pb)
            # One-sided probability of at least this many agreements under that null.
            from scipy.stats import binom  # noqa: PLC0415
            p = float(binom.sf(agree - 1, len(shared), chance))
            lines.append(
                f"| `{left}` vs `{right}` | {len(shared)} | {agree} | {agree / len(shared):.3f} "
                f"| {chance:.3f} | {p:.3f} |"
            )
        lines += [
            "",
            "`Chance` is the agreement two independent labellers would reach drawing at each "
            "model's own robust rate. Both rates are high, so a high agreement rate is worth "
            "little until the shared set is large; read the p column, not the rate.",
        ]
    upsert_section(RESULTS, "Self-generated olympiad labels", "\n".join(lines))
    print("\n".join(lines))


if __name__ == "__main__":
    main()
