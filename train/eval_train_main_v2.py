"""Two questions the organizers' own labels can answer that our own data cannot.

`aimo-interp/train-main-v2` is the only public table with official labels on **olympiad**
problems for the small-track models, and the only one where a problem is labelled for several
models at once. That makes it the out-of-population test our training set cannot provide: 137
of our 138 DeepSeek instances are Hendrycks MATH.

1. **Is robustness a property of the problem or of the model?** If two models labelled on the
   same problem usually agree, one problem-level model serves all four and labels are fungible
   across models. Chance agreement is not 50% here -- the split is 73% robust -- so the
   observed rate is compared against `p^2 + (1-p)^2` and against a label permutation test.

2. **Does the shipped text block transfer to olympiad problems?** It is scored against the 34
   labelled small-track rows with a bootstrap CI. This is the direct test of the risk PLAN.md
   ranks first, and the CI matters more than the point estimate at n=34.

Neither question can be answered from `data/small_track/`, and both feed PROGRESS Findings
36-37. Writes the `train-main-v2 transfer` section of RESULTS.md.

Run:  uv run python ../train/eval_train_main_v2.py
"""

from __future__ import annotations

import argparse
import itertools
import re
from pathlib import Path

import joblib
import numpy as np
import pandas as pd
from huggingface_hub import hf_hub_download
from sklearn.metrics import accuracy_score, roc_auc_score

import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "train"))
from results_io import upsert_section  # noqa: E402

DATASET = "aimo-interp/train-main-v2"
REVISION = "23791d9b120132087877b0459f953d5959fc8455"
PARQUET = "data/train-00000-of-00001.parquet"
ARTIFACT = ROOT / "submission" / "e11-text-stagea" / "artifacts" / "e11_deepseek.joblib"
RESULTS = ROOT / "RESULTS.md"

SMALL_TRACK = (
    "Qwen/Qwen3.5-4B",
    "Skywork/Skywork-OR1-Math-7B",
    "allenai/Olmo-3-7B-Think",
    "deepseek-ai/DeepSeek-R1-0528-Qwen3-8B",
)


def normalise(text: str) -> str:
    return re.sub(r"\s+", " ", text).strip().lower()


def agreement(frame: pd.DataFrame) -> tuple[int, int]:
    """Pairs of (problem, model A, model B) where both are labelled, and how many agree."""
    table = frame.pivot_table(
        index="normalised", columns=["model_id", "reasoning_effort"], values="is_robust", aggfunc="first"
    )
    agree = total = 0
    for left, right in itertools.combinations(table.columns, 2):
        both = table[[left, right]].dropna()
        total += len(both)
        agree += int((both[left] == both[right]).sum())
    return agree, total


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--revision", default=REVISION)
    parser.add_argument("--n-boot", type=int, default=5000)
    parser.add_argument("--n-permutations", type=int, default=2000)
    parser.add_argument("--seed", type=int, default=0)
    args = parser.parse_args()

    path = hf_hub_download(DATASET, PARQUET, repo_type="dataset", revision=args.revision)
    table = pd.read_parquet(path)
    labelled = table[table["is_robust"].notna()].copy()
    labelled["normalised"] = labelled["problem"].map(normalise)

    rng = np.random.default_rng(args.seed)
    lines: list[str] = [
        f"Source: `{DATASET}` @ `{args.revision[:12]}`, regenerated by `train/eval_train_main_v2.py`.",
        "",
        "### Is robustness a property of the problem or of the model?",
        "",
        "| Scope | Agreeing pairs | Rate |",
        "| --- | --- | --- |",
    ]

    base_rate = float(labelled["is_robust"].mean())
    chance = base_rate**2 + (1 - base_rate) ** 2
    scopes = {
        "all configurations": labelled,
        "small-track models only": labelled[labelled["model_id"].isin(SMALL_TRACK)],
    }
    for name, frame in scopes.items():
        agree, total = agreement(frame)
        rate = f"{agree / total:.3f}" if total else "n/a"
        lines.append(f"| {name} | {agree} / {total} | {rate} |")
    lines.append(f"| chance, at a {base_rate:.3f} robust base rate | — | {chance:.3f} |")

    observed_agree, observed_total = agreement(labelled)
    hits = 0
    for _ in range(args.n_permutations):
        shuffled = labelled.copy()
        shuffled["is_robust"] = rng.permutation(shuffled["is_robust"].values)
        agree, total = agreement(shuffled)
        if total and agree / total >= observed_agree / observed_total:
            hits += 1
    p_value = (hits + 1) / (args.n_permutations + 1)
    lines += [
        "",
        f"Label permutation test over {args.n_permutations} draws: **p = {p_value:.4f}**.",
        "",
        "### Does the shipped text block transfer to olympiad problems?",
        "",
    ]

    artifact = joblib.load(ARTIFACT)
    small = labelled[labelled["model_id"].isin(SMALL_TRACK)].copy()
    small["text_prob"] = artifact["text_model"].predict_proba(list(small["problem"]))[:, 1]
    y = small["is_robust"].astype(bool).to_numpy()
    p = small["text_prob"].to_numpy()

    boot = []
    for _ in range(args.n_boot):
        idx = rng.integers(0, len(y), len(y))
        if len(np.unique(y[idx])) > 1:
            boot.append(roc_auc_score(y[idx], p[idx]))
    low, high = np.percentile(boot, [2.5, 97.5])

    lines += [
        "| Scope | n | ROC-AUC | 95% CI |",
        "| --- | --- | --- | --- |",
        f"| all small-track rows | {len(y)} | {roc_auc_score(y, p):.3f} | [{low:.3f}, {high:.3f}] |",
    ]
    for model_id in SMALL_TRACK:
        subset = small[small["model_id"] == model_id]
        truth = subset["is_robust"].astype(bool)
        auc = f"{roc_auc_score(truth, subset['text_prob']):.3f}" if truth.nunique() > 1 else "single class"
        lines.append(f"| {model_id} | {len(subset)} | {auc} | — |")

    best_accuracy, best_threshold = max((accuracy_score(y, p >= t), t) for t in np.unique(p))
    lines += [
        "",
        f"- Always-robust scores **{y.mean():.3f}** on this set; the best threshold sweep reaches "
        f"**{best_accuracy:.3f}** at `p >= {best_threshold:.3f}`, chosen in-sample and so optimistic.",
        f"- The train split is **{base_rate:.3f}** robust, but the dataset card calls the validation "
        "set close to balanced and Finding 27's all-False probe scored 0.50. Do not calibrate a "
        "threshold on the train prevalence.",
    ]
    upsert_section(RESULTS, "train-main-v2 transfer", "\n".join(lines))
    print("\n".join(lines))
    print(f"\nwrote the 'train-main-v2 transfer' section of {RESULTS}")


if __name__ == "__main__":
    main()
